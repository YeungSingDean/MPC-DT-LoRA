"""Shared rollout utilities: run a controller for one episode, collect trajectory + metrics.

Important for offline RL / Decision Transformer:
- requested_actions: actions proposed by the controller;
- applied_actions: actions actually executed by the environment after workload /
  thermal safety projection.

For DT training, the default loader uses applied_actions when they are available,
because the observed next state and reward are generated by the applied action.

For DT evaluation, if the controller implements ``update_applied_action()``,
the latest action stored in the controller history is replaced by the action
actually executed by the environment. This keeps the rollout context consistent
with the action semantics used during training.

Thermal trace:
- ``t_inlet`` is collected per step and saved alongside the trajectory. This is
  required to build a thermal boundary pool for V3 post-training (samples near
  27 C), which the action-only correction signal cannot capture.
"""

from __future__ import annotations

import numpy as np


def run_episode(
    env,
    controller,
    seed: int | None = None,
    start_hour: int | None = None,
) -> dict:
    """Run one complete episode and return trajectory data plus episode metrics."""
    options = {"start_hour": start_hour} if start_hour is not None else None
    obs, info = env.reset(seed=seed, options=options)
    reset_info = dict(info)

    if hasattr(controller, "reset"):
        controller.reset()

    observations = []
    requested_actions = []
    applied_actions = []
    rewards = []
    infos = []
    t_inlet_trace = []          # thermal boundary trace (one float per step)

    done = False
    while not done:
        # 1. Controller proposes an action.
        action = controller.act(obs, info)
        observations.append(np.asarray(obs, dtype=np.float32))

        # 2. Environment executes the action. Safety/workload projections may modify it.
        next_obs, reward, terminated, truncated, info = env.step(action)

        requested_action = np.asarray(action, dtype=np.float32)
        applied_action = np.asarray(
            info.get("applied_action", requested_action),
            dtype=np.float32,
        )

        # 3. Keep DT action history consistent with the actual transition.
        if hasattr(controller, "update_applied_action"):
            controller.update_applied_action(applied_action)

        # 4. Decision Transformer return-to-go bookkeeping.
        if hasattr(controller, "update_reward"):
            controller.update_reward(reward)

        requested_actions.append(requested_action)
        applied_actions.append(applied_action)
        rewards.append(float(reward))
        infos.append(info)
        t_inlet_trace.append(float(info.get("t_inlet", np.nan)))

        obs = next_obs
        done = terminated or truncated

    reward_terms: dict[str, float] = {}
    for step_info in infos:
        for name, value in step_info.get("reward_terms", {}).items():
            reward_terms[name] = reward_terms.get(name, 0.0) + float(value)

    requested_actions_arr = np.stack(requested_actions).astype(np.float32)
    applied_actions_arr = np.stack(applied_actions).astype(np.float32)

    return {
        "observations": np.stack(observations).astype(np.float32),
        "actions": requested_actions_arr,  # backward-compatible legacy field
        "requested_actions": requested_actions_arr,
        "applied_actions": applied_actions_arr,
        "rewards": np.asarray(rewards, dtype=np.float32),
        "episode_return": float(np.sum(rewards)),
        "metrics": env.episode_summary(),
        "reward_terms": reward_terms,
        "reset_info": reset_info,
        "t_inlet": np.asarray(t_inlet_trace, dtype=np.float32),
    }


def save_trajectories(
    path: str,
    trajectories: list[dict],
    source: str,
):
    """Save trajectories to a compressed NPZ file.

    Both requested and applied actions are saved. Rewards and next observations
    correspond to applied_actions.

    If every trajectory carries a ``t_inlet`` trace, it is stored as well and is
    used by downstream scripts to build a thermal boundary pool.
    """
    if not trajectories:
        raise ValueError("Cannot save an empty trajectory list.")

    observations = np.stack(
        [t["observations"] for t in trajectories]
    ).astype(np.float32)

    requested_actions = np.stack([
        t.get("requested_actions", t["actions"])
        for t in trajectories
    ]).astype(np.float32)

    applied_actions = np.stack([
        t.get("applied_actions", t.get("requested_actions", t["actions"]))
        for t in trajectories
    ]).astype(np.float32)

    rewards = np.stack(
        [t["rewards"] for t in trajectories]
    ).astype(np.float32)

    returns = np.asarray(
        [t["episode_return"] for t in trajectories],
        dtype=np.float32,
    )

    # Optional thermal trace: only saved when every trajectory provides it,
    # so old-format producers keep working without surprising shape errors.
    if all("t_inlet" in t and t["t_inlet"] is not None for t in trajectories):
        t_inlet = np.stack(
            [np.asarray(t["t_inlet"], dtype=np.float32) for t in trajectories]
        ).astype(np.float32)
    else:
        t_inlet = None
        print(
            "[warning] save_trajectories: some trajectories lack 't_inlet'; "
            "thermal boundary pool will be unavailable for this file."
        )

    payload = dict(
        observations=observations,
        actions=requested_actions,  # keep legacy meaning
        requested_actions=requested_actions,
        applied_actions=applied_actions,
        rewards=rewards,
        returns=returns,
        source=source,
    )
    if t_inlet is not None:
        payload["t_inlet"] = t_inlet

    np.savez_compressed(path, **payload)


def load_trajectories(
    paths: list[str],
    use_applied_actions: bool = True,
) -> list[dict]:
    """Load trajectories for offline RL / Decision Transformer training.

    If use_applied_actions=True (recommended), the returned ``actions`` field
    uses applied_actions whenever available, because reward_t and state_{t+1}
    were generated by the applied action.

    Old trajectory files without applied_actions remain loadable and fall back
    to the legacy actions field with a warning. Files without a ``t_inlet``
    trace are also loadable; the per-trajectory ``t_inlet`` field is then None.
    """
    out: list[dict] = []

    for p in paths:
        d = np.load(p, allow_pickle=True)

        required = ("observations", "rewards", "returns")
        missing = [key for key in required if key not in d]
        if missing:
            raise ValueError(f"{p} is missing required arrays: {missing}")

        if "requested_actions" in d:
            requested = d["requested_actions"]
        elif "actions" in d:
            requested = d["actions"]
        else:
            raise ValueError(f"{p} does not contain an actions array.")

        if "applied_actions" in d:
            applied = d["applied_actions"]
            has_applied = True
        else:
            applied = requested
            has_applied = False
            if use_applied_actions:
                print(
                    f"[warning] {p} has no 'applied_actions'. "
                    "Falling back to legacy 'actions'. "
                    "Regenerate this trajectory file for action-consistent DT training."
                )

        if "t_inlet" in d:
            t_inlet = d["t_inlet"]
            has_t_inlet = True
        else:
            t_inlet = None
            has_t_inlet = False
            print(
                f"[warning] {p} has no 't_inlet' trace. "
                "Thermal boundary samples will be unavailable for this file. "
                "Regenerate with the updated rollout.py to enable them."
            )

        source_value = d["source"] if "source" in d else "unknown"
        if isinstance(source_value, np.ndarray) and source_value.shape == ():
            source_value = source_value.item()
        source_value = str(source_value)

        n_traj = len(d["returns"])
        for i in range(n_traj):
            training_actions = applied[i] if use_applied_actions else requested[i]

            out.append({
                "observations": np.asarray(
                    d["observations"][i], dtype=np.float32
                ),
                "actions": np.asarray(
                    training_actions, dtype=np.float32
                ),
                "requested_actions": np.asarray(
                    requested[i], dtype=np.float32
                ),
                "applied_actions": np.asarray(
                    applied[i], dtype=np.float32
                ),
                "rewards": np.asarray(
                    d["rewards"][i], dtype=np.float32
                ),
                "source": source_value,
                "has_true_applied_actions": has_applied,
                "t_inlet": (
                    np.asarray(t_inlet[i], dtype=np.float32)
                    if has_t_inlet else None
                ),
            })

    return out